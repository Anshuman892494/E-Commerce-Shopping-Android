@Composable
fun StockBadge(stock: Int, modifier: Modifier = Modifier) {
    val (bgColor, textColor, text) = when {
        stock <= 0 -> Triple(ErrorRedContainer, ErrorRed, "Out of Stock")
        stock <= 3 -> Triple(WarningAmberContainer, WarningAmber, "Only $stock left")
        else -> Triple(SuccessGreenContainer, SuccessGreen, "In Stock")
    }

    Box(
        modifier = modifier
            .clip(RoundedCornerShape(6.dp))
            .background(bgColor)
            .padding(horizontal = 8.dp, vertical = 4.dp),
        contentAlignment = Alignment.Center
    ) {
        Text(
            text = text,
            color = textColor,
            style = MaterialTheme.typography.labelSmall,
            fontWeight = FontWeight.Bold
        )
    }
}

